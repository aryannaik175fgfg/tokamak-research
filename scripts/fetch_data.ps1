param(
    [ValidateSet("all", "itpa", "mhd", "tokamark", "robustness", "verify")]
    [string]$Stage = "all",
    [switch]$TokamarkOneBatch
)

$ErrorActionPreference = "Stop"
$Root = Split-Path $PSScriptRoot -Parent
Set-Location $Root

$Data = Join-Path $Root "data"
$Itpa = Join-Path $Data "itpa"
$Mhd = Join-Path $Data "mhd_64"
$Tok = Join-Path $Data "tokamark"
$Dis = Join-Path $Data "disruption_exports"
@($Data, $Itpa, $Mhd, $Tok, $Dis) | ForEach-Object { New-Item -ItemType Directory -Force -Path $_ | Out-Null }

# Prefer system 3.11 (CUDA torch); project .venv may be incomplete on Windows.
$Py = "py -3.11"

function Write-PathsYaml {
    $xlsx = Join-Path $Itpa "HDB5V2.3.xlsx"
    $paths = @"
# Auto-generated by scripts/fetch_data.ps1
itpa_globals_path: $($xlsx.Replace('\','/'))
itpa_pr08_path: data/itpa/pr08
mhd_local_path: data/mhd_64
tokamark_local_path: data/tokamark/restored_zarrs
disruption_export_d3d: null
disruption_export_cmod: null
"@
    Set-Content -Path (Join-Path $Data "paths.yaml") -Value $paths -Encoding utf8
}

if ($Stage -in @("all", "itpa")) {
    Write-Host "== ITPA DB5.2.3 =="
    $dest = Join-Path $Itpa "HDB5V2.3.xlsx"
    if (-not (Test-Path $dest)) {
        $urls = @(
            "https://osf.io/download/km7fy/",
            "https://dataspace.princeton.edu/bitstream/handle/88435/dsp01m900nx49h/HDB5V2.3.xlsx?sequence=1&isAllowed=y"
        )
        $got = $false
        foreach ($url in $urls) {
            try {
                Invoke-WebRequest -Uri $url -OutFile $dest -UseBasicParsing -MaximumRedirection 5 -Headers @{"User-Agent"="Mozilla/5.0"}
                if ((Get-Item $dest).Length -gt 1e6) { $got = $true; Write-Host "Downloaded $dest"; break }
            } catch { Write-Warning $_.Exception.Message }
        }
        if (-not $got) {
            Write-Warning "Auto-download failed. Save DB5.2.3.xlsx from https://osf.io/hrqcf/ to $dest"
        }
    } else {
        Write-Host "Already present: $dest"
    }
    Write-Host "PR08: place UFILE bundles under data/itpa/pr08/ (see data/README.md)"
}

if ($Stage -in @("all", "mhd")) {
    Write-Host "== MHD_64 (The Well) =="
    & $Py -m pip install "the_well[benchmark]" huggingface_hub -q
    $hf = Join-Path $Mhd "hf_cache"
    New-Item -ItemType Directory -Force -Path $hf | Out-Null
    $env:HF_HOME = $hf
    $mhdPy = @"
from pathlib import Path
try:
    from the_well.utils.download import well_download
    base = Path(r'$($Mhd -replace "'","''")')
    well_download(base_path=str(base), dataset='MHD_64', split='valid')
    print('MHD_64 valid split under', base)
except Exception as e:
    print('well_download failed:', e)
    print('Fallback: stream with path=hf://datasets/polymathic-ai/MHD_64/data/train in well_mhd_loader (no full download).')
"@
    & $Py -c $mhdPy
}

if ($Stage -in @("all", "robustness")) {
    Write-Host "== TokaMark robustness subset (~650 MB) =="
    & $Py (Join-Path $Root "scripts\fetch_tokamark_subset.py")
}

if ($Stage -in @("all", "tokamark")) {
    Write-Host "== TokaMark =="
    & $Py -m pip install huggingface_hub -q
    if ($TokamarkOneBatch -or $Stage -eq "all") {
        Write-Host "Downloading ONE dev batch (~size varies). Full benchmark is ~565 GB on UKAEA-IBM-STFC/tokamark-v1"
        $dlPy = @"
from huggingface_hub import hf_hub_download
from pathlib import Path
base = Path(r'$($Tok -replace "'","''")')
for name in ('batch_00000.tar', 'unpack_all.py'):
    p = hf_hub_download(repo_id='UKAEA-IBM-STFC/tokamark-v1', filename=name, repo_type='dataset', local_dir=str(base))
    print('got', name, '->', p)
"@
        & $Py -c $dlPy
    } else {
        Write-Host "Use: hf download UKAEA-IBM-STFC/tokamark-v1 --repo-type dataset --local-dir data/tokamark"
    }
    $unpack = Join-Path $Tok "unpack_all.py"
    $zarrs = Join-Path $Tok "restored_zarrs"
    if ((Test-Path $unpack) -and (Get-ChildItem $Tok -Filter "batch_*.tar")) {
        Write-Host "Unpacking batches -> $zarrs"
        & $Py $unpack $Tok $zarrs --workers 4
    } else {
        Write-Host "Then unpack: python $unpack $Tok $zarrs --workers 4"
    }
}

if ($Stage -in @("all", "verify")) {
    Write-Host "== Verify =="
    & $Py (Join-Path $Root "scripts/verify_data.py")
}

Write-PathsYaml
Write-Host "Wrote data/paths.yaml"